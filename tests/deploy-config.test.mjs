/**
 * The Cloudflare Workers build, as configuration.
 *
 * `Workers Builds: nex` failed on every push for weeks. It was not the code: the
 * project was wired to `npx wrangler preview`, an **open-beta** command that
 * publishes a preview deployment instead of the Worker, and the build ran
 * against a checkout with no `dist/` (generated, git-ignored) so Wrangler
 * refused before it ever got that far.
 *
 * These assertions are the guard rails: the config builds itself, the deploy
 * command cannot regress to `preview`, and the docs say the same thing.
 */
import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');
const read = (file) => fs.readFileSync(path.join(ROOT, file), 'utf8');

/** The committed config, with comments stripped (it is jsonc). */
function config() {
  const raw = read('wrangler.jsonc');
  const stripped = raw
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .split('\n')
    .map((line) => line.replace(/(^|[^:])\/\/.*$/, '$1'))
    .join('\n');
  return JSON.parse(stripped);
}

test('the Worker config builds dist/ itself, because dist is generated', () => {
  const cfg = config();
  assert.equal(cfg.name, 'alphacode');
  assert.equal(cfg.assets?.directory, 'dist');
  assert.equal(cfg.assets?.not_found_handling, 'single-page-application');
  assert.equal(cfg.build?.command, 'npm run build', 'a clean checkout has no dist/ — wrangler must build it');
  assert.ok(fs.existsSync(path.join(ROOT, '.gitignore')));
  assert.match(read('.gitignore'), /^dist\/$/m, 'dist is git-ignored, which is exactly why build.command exists');
});

test('the config is valid jsonc and carries no deploy-time secret', () => {
  const raw = read('wrangler.jsonc');
  assert.ok(config(), 'parses');
  assert.equal(/account_id|api_token|API_KEY/i.test(raw), false, 'no credentials in a committed config');
  assert.equal(cfgHasMain(), false, 'assets-only Worker: no main entry, nothing to bundle');
});

function cfgHasMain() {
  return Boolean(config().main);
}

test('nothing in the repo tells anyone to run the beta preview command', () => {
  const files = ['README.md', 'docs/DEPLOY.md', 'package.json', 'scripts/deploy-cloudflare.mjs'];
  for (const file of files) {
    const text = read(file);
    // The docs are allowed to *warn* about `wrangler preview`; they must never
    // present it as a command to run.
    // Judge the whole paragraph the mention lives in: a warning block can be
    // several lines long, and the sentence that makes it a warning may come after
    // the command.
    const paragraphs = text.split(/\n\s*\n/);
    for (const paragraph of paragraphs) {
      if (!/wrangler preview(?! delete| secret| base-config)/.test(paragraph)) continue;
      const isWarning = /do not use|never use|open[ -]beta|deprecat|❌|not `?npx wrangler preview/i.test(paragraph);
      assert.ok(isWarning, `${file}: "${paragraph.slice(0, 80).replace(/\n/g, ' ')}…" presents wrangler preview without a warning`);
    }
  }
});

test('the npm scripts expose a real deploy and a dry run', () => {
  const scripts = JSON.parse(read('package.json')).scripts;
  assert.equal(scripts['deploy:worker'], 'npm run build && wrangler deploy');
  assert.match(scripts['check:worker'], /wrangler deploy --dry-run/);
  assert.equal(/wrangler preview/.test(JSON.stringify(scripts)), false);
});

test('the documented Workers Build settings match the config', () => {
  const deploy = read('docs/DEPLOY.md');
  assert.match(deploy, /Deploy command: `npx wrangler deploy`/);
  assert.match(deploy, /Build command: leave it empty/i);
  assert.match(deploy, /wrangler preview/i, 'the deprecation is documented');
  const readme = read('README.md');
  assert.match(readme, /npx wrangler deploy/);
  assert.match(readme, /open-beta|open beta/i);
});

test('allow-all-or-nothing: the static headers still set the security basics', () => {
  // `_headers` is generated by the build; the middleware must not disagree with
  // it about the isolation headers the sandbox needs.
  const middleware = read('functions/_middleware.js');
  assert.match(middleware, /Cross-Origin-Opener-Policy/);
  assert.match(middleware, /Cross-Origin-Embedder-Policy/);
  assert.match(middleware, /stackblitz\.com/, 'frame-src must allow the WebContainers iframe');
});
